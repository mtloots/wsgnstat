## Parity harness, R front: prints every value of every entry point of the shared C back-end as
## "label %.15e", in the same order as parity_py.py. Run through parity_run.sh, which first checks
## that the two copies of the C source agree. Usage: Rscript parity_R.R [library path]
args <- commandArgs(TRUE)
if (length(args) >= 1) library(wsgnstat, lib.loc = args[1]) else library(wsgnstat)
out <- function(label, v) {
  v <- as.numeric(v)
  txt <- ifelse(is.na(v), "nan", ifelse(is.infinite(v), ifelse(v > 0, "inf", "-inf"), sprintf("%.15e", v)))
  cat(sprintf("%s[%d] %s\n", label, seq_along(v) - 1L, txt), sep = "")
}
cplx <- function(label, z) { out(paste0(label, ".re"), Re(z)); out(paste0(label, ".im"), Im(z)) }
x <- c(-3, -0.7, 0, 0.4, 1.9, 5)
th <- c(0, 0.3, 1.1, 2.5, 3.9, 5.2, 6.2)
tt <- c(0, 0.5, 1, 2, 3, 7.5, 20)
shapes <- c(0.05, 0.1, 0.3, 0.7, 1, 1.5, 2, 3.5, 8)
for (be in shapes) {
  lab <- sprintf("b%.2f", be)
  out(paste0("dsgn.", lab), dsgn(x, 0.2, 0.8, be, 0.3, 0.7))
  out(paste0("psgn.", lab), psgn(x, 0.2, 0.8, be, 0.3, 0.7))
  cplx(paste0("cfsgn.", lab), cfsgn(tt, 0.2, 0.8, be, 0.3, 0.7))
  cplx(paste0("cfsgn.tol8.", lab), cfsgn(tt, 0.2, 0.8, be, 0.3, 0.7, tol = 1e-8))
  cplx(paste0("cfser.", lab), suppressWarnings(cfsgn(tt, 0.2, 0.8, be, 0.3, 0.7, method = "series")))
  tm <- trig_moments(6, 1.3, be, 0.35, sigma = 0.5)
  out(paste0("trigA.", lab), tm$A); out(paste0("trigB.", lab), tm$B)
  tm0 <- trig_moments(3, 1.3, be, 0.35)
  out(paste0("trig0A.", lab), tm0$A); out(paste0("trig0B.", lab), tm0$B)
  out(paste0("decay.", lab), trig_decay(be, 0.35, 0.5))
  out(paste0("dwsgn.", lab), dwsgn(th, 1.3, be, 0.35, sigma = 0.5))
  out(paste0("dwsgnlog.K3.", lab), dwsgn(th, 1.3, be, 0.35, K = 3, sigma = 0.5, log = TRUE))
  out(paste0("dwsgn0.", lab), dwsgn(th, 1.3, be, 0.35))
  out(paste0("pwsgn.", lab), pwsgn(th, 1.3, be, 0.35, sigma = 0.5))
  out(paste0("qwsgn.", lab), qwsgn(c(0.01, 0.25, 0.5, 0.9), 1.3, be, 0.35, sigma = 0.5))
  out(paste0("nll.", lab), .C(wsgnstat:::C_wsgn_nll, as.double(th), length(th), 1.3, 0.5, be, 0.35, 50L, out = double(1))$out)
  out(paste0("gll.", lab), grouped_loglik(th, pi / 18, 1.3, 0.5, 0.35, be))
}
## deterministic samples: quantiles of van der Corput points, identical in both fronts
vdc <- function(n) rowSums(outer(seq_len(n), 1:20, function(i, j) ((i %/% 2^(j - 1)) %% 2) / 2^j))
s1 <- qwsgn(vdc(120), 1, 1.6, 0.3, sigma = 0.4)
s2 <- qwsgn(vdc(90), 2, 0.6, 0.4, sigma = 0.25)
h <- pi / 18
s3 <- (round(qwsgn(vdc(100), 3, 1.2, 0.45, sigma = 0.3) / h) * h) %% (2 * pi)
fo <- function(f) c(f$par, f$logLik, f$nfev, f$at_floor, if (is.null(f$se)) numeric(0) else f$se)
out("fit.s1.info", fo(fit_wsgn(s1)))
out("fit.s1.vcov", fit_wsgn(s1)$vcov)
out("fit.s1.sym", fo(fit_wsgn(s1, symmetric = TRUE)))
out("fit.s2", fo(fit_wsgn(s2, se = "none")))
out("fit.s2.floor", fo(fit_wsgn(s2, beta_floor = 1.2, se = "none")))
out("fit.s3.grouped", fo(fit_wsgn(s3, resolution = h, se = "none")))
pr <- profile_wsgn(s2, c(0.1, 0.5, 1, 2))
out("profile.s2", unlist(pr))
pr3 <- profile_wsgn(s3, c(0.3, 1), resolution = h)
out("profile.s3", unlist(pr3))
a2 <- wsgnstat:::.fit_args(s2, NULL, NULL, 0, FALSE, 0.4, 50)
f2 <- fit_wsgn(s2, se = "none")
d2 <- qwsgn(vdc(90 * 3), f2$par["mu"], f2$par["beta"], f2$par["lam"], sigma = f2$par["sigma"])
b2 <- wsgnstat:::.fit_batch(d2, a2, 3, f2$par)
out("batch.s2.est", t(b2$est)); out("batch.s2.se", c(b2$se, b2$frac_beta_lt1))
a3 <- wsgnstat:::.fit_args(s3, NULL, h, 0, FALSE, 0.4, 50)
f3 <- fit_wsgn(s3, resolution = h, se = "none")
d3 <- qwsgn(vdc(100 * 2), f3$par["mu"], f3$par["beta"], f3$par["lam"], sigma = f3$par["sigma"])
b3 <- wsgnstat:::.fit_batch(d3, a3, 2, f3$par)
out("batch.s3.est", t(b3$est)); out("batch.s3.se", c(b3$se, b3$frac_beta_lt1))
